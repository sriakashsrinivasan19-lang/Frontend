// basic calculation
let shirtPrice = 650;
let pantPrice = 800;

console.log(shirtPrice + pantPrice);
console.log(shirtPrice - pantPrice);
console.log(shirtPrice * pantPrice);
console.log(shirtPrice / pantPrice);
console.log(shirtPrice % pantPrice);


// assignment operators
let collegeFees = 20000;
collegeFees += 100;
console.log(collegeFees);

let shoePrice = 650;
shoePrice -= 100;
console.log(shoePrice);

let amountValue = 30;
amountValue *= 2;
console.log(amountValue);

let medicinePrice = 50;
medicinePrice /= 2;
console.log(medicinePrice);

// comparison operator

let voterAge = 18;
console.log(voterAge == 19);
console.log(voterAge === 18);
console.log(voterAge > 16);
console.log(voterAge < 19);
console.log(voterAge >= 20);
console.log(voterAge <= 20);

// logical operator

let priceValue = 200;
